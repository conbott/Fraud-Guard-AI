"""Synthetic credit card transaction generator for testing and CI/CD pipelines.

CRITICAL NOTICE:
Synthetic data generated by this module is purely mathematical simulation designed
for schema validation, unit testing, and continuous integration smoke tests. It must
NEVER be represented as genuine financial transactions or used to claim real-world
banking-grade predictive performance.
"""

from pathlib import Path
from typing import Optional, Tuple

import numpy as np
import pandas as pd

from src.config import load_model_config


def generate_synthetic_transactions(
    n_samples: int = 2000,
    fraud_rate: float = 0.015,
    random_seed: int = 42,
) -> pd.DataFrame:
    """Generate a synthetic dataset mirroring the Kaggle Credit Card Fraud schema.

    Schema:
      - Time: float seconds elapsed (0 to ~172,800 seconds / 2 days)
      - V1 to V28: float numerical PCA features
      - Amount: transaction amount (positive float)
      - Class: binary integer (0 = legitimate, 1 = fraudulent)
    """
    rng = np.random.default_rng(random_seed)

    n_fraud = int(round(n_samples * fraud_rate))
    n_normal = n_samples - n_fraud

    # Generate Time (increasing sequence with small noise)
    times = np.sort(rng.uniform(0, 172800, size=n_samples))

    # Normal transactions: standard Gaussian features
    v_normal = rng.normal(loc=0.0, scale=1.0, size=(n_normal, 28))
    # Fraud transactions: shift key discriminative features (V10, V12, V14 negative, V4, V11 positive)
    v_fraud = rng.normal(loc=0.0, scale=1.2, size=(n_fraud, 28))
    # Features V14, V12, V10, V17 are known in literature to have negative shifts in fraud
    v_fraud[:, 13] -= 3.5  # V14
    v_fraud[:, 11] -= 3.0  # V12
    v_fraud[:, 9] -= 2.5   # V10
    v_fraud[:, 16] -= 2.0  # V17
    # Features V4, V11 have positive shifts in fraud
    v_fraud[:, 3] += 2.5   # V4
    v_fraud[:, 10] += 2.0  # V11

    # Amounts: log-normal distribution for normal; higher variance for fraud
    amounts_normal = np.round(rng.lognormal(mean=3.2, sigma=1.2, size=n_normal), 2)
    amounts_fraud = np.round(rng.lognormal(mean=4.1, sigma=1.5, size=n_fraud), 2)

    # Combine
    v_all = np.vstack([v_normal, v_fraud])
    amounts_all = np.concatenate([amounts_normal, amounts_fraud])
    classes = np.array([0] * n_normal + [1] * n_fraud, dtype=int)

    # Shuffle to interleave normal and fraud
    shuffle_idx = rng.permutation(n_samples)
    v_shuffled = v_all[shuffle_idx]
    amounts_shuffled = amounts_all[shuffle_idx]
    classes_shuffled = classes[shuffle_idx]
    times_shuffled = times[shuffle_idx]

    feature_cols = [f"V{i}" for i in range(1, 29)]
    df = pd.DataFrame(v_shuffled, columns=feature_cols)
    df.insert(0, "Time", times_shuffled)
    df["Amount"] = amounts_shuffled
    df["Class"] = classes_shuffled

    return df


def create_test_fixtures(
    output_dir: Optional[Path] = None,
    fixture_samples: int = 300,
    synthetic_samples: int = 3000,
) -> Tuple[Path, Path]:
    """Generate both small test fixture and standard synthetic dataset."""
    config = load_model_config()
    target_dir = output_dir or config.synthetic_path.parent
    target_dir.mkdir(parents=True, exist_ok=True)

    fixture_path = target_dir / "test_fixture.csv"
    synthetic_path = target_dir / "synthetic_transactions.csv"

    # Small test fixture (300 rows, ~5% fraud for fast stable unit tests)
    fixture_df = generate_synthetic_transactions(
        n_samples=fixture_samples, fraud_rate=0.05, random_seed=42
    )
    fixture_df.to_csv(fixture_path, index=False)

    # Medium synthetic dataset (3000 rows, 2% fraud for smoke tests and CI)
    synthetic_df = generate_synthetic_transactions(
        n_samples=synthetic_samples, fraud_rate=0.02, random_seed=123
    )
    synthetic_df.to_csv(synthetic_path, index=False)

    return fixture_path, synthetic_path


if __name__ == "__main__":
    fp, sp = create_test_fixtures()
    print(f"Created test fixture at: {fp}")
    print(f"Created synthetic dataset at: {sp}")
